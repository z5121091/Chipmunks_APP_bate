export interface HelpSearchResult {
  topic: HelpTopic;
  article: HelpArticle;
}

export function searchHelp(query: string): HelpSearchResult[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return HELP_TOPICS.flatMap((topic) =>
    topic.articles.flatMap((article) => {
      const text = [
        topic.title,
        topic.summary,
        article.title,
        article.summary,
        ...article.steps,
        article.note || '',
        ...(article.keywords || []),
      ]
        .join(' ')
        .toLocaleLowerCase();
      return words.every((word) => text.includes(word)) ? [{ topic, article }] : [];
    })
  );
}
